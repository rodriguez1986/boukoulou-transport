CREATE TABLE IF NOT EXISTS security_login_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL,
    event VARCHAR(60) NOT NULL,
    component VARCHAR(60) NOT NULL,
    scope VARCHAR(20) NOT NULL,
    ref VARCHAR(128) NOT NULL,
    count INTEGER NOT NULL,
    window_seconds INTEGER NOT NULL,
    CONSTRAINT security_login_alert_scope CHECK (scope IN ('user_ref','client_ref'))
);
CREATE INDEX IF NOT EXISTS ix_security_login_alerts_time ON security_login_alerts (occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_security_login_alerts_scope_id ON security_login_alerts (scope, id DESC);
