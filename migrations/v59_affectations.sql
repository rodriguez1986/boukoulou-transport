BEGIN;

-- 1. Capacite debout des vehicules
ALTER TABLE vehicles
ADD COLUMN IF NOT EXISTS standing_capacity INTEGER NOT NULL DEFAULT 0;

ALTER TABLE vehicles
DROP CONSTRAINT IF EXISTS ck_vehicles_standing_capacity;

ALTER TABLE vehicles
ADD CONSTRAINT ck_vehicles_standing_capacity
CHECK (standing_capacity >= 0);

-- 2. Liaison chauffeur / compte utilisateur
ALTER TABLE drivers
ADD COLUMN IF NOT EXISTS user_id INTEGER;

CREATE UNIQUE INDEX IF NOT EXISTS ux_drivers_user_id
ON drivers(user_id);

-- Cle etrangere vers les utilisateurs
ALTER TABLE drivers
DROP CONSTRAINT IF EXISTS fk_drivers_user_id;

ALTER TABLE drivers
ADD CONSTRAINT fk_drivers_user_id
FOREIGN KEY (user_id)
REFERENCES users(id);

-- 3. Affectation des controleurs aux courses
CREATE TABLE IF NOT EXISTS trip_controllers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trips(id),
    controller_id INTEGER NOT NULL REFERENCES users(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_trip_controller UNIQUE (trip_id, controller_id)
);

CREATE INDEX IF NOT EXISTS ix_trip_controllers_controller_id
ON trip_controllers(controller_id);

COMMIT;