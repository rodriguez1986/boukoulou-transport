BEGIN;

-- 1. Villes
CREATE TABLE IF NOT EXISTS cities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id INTEGER NOT NULL REFERENCES countries(id),
    name VARCHAR(120) NOT NULL,
    CONSTRAINT uq_cities_country_name UNIQUE (country_id, name),
    CONSTRAINT uq_cities_id_country UNIQUE (id, country_id)
);

-- 2. Arrêts
CREATE TABLE IF NOT EXISTS stops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id INTEGER NOT NULL REFERENCES cities(id),
    name VARCHAR(160) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    CONSTRAINT uq_stops_city_name UNIQUE (city_id, name),
    CONSTRAINT uq_stops_id_city UNIQUE (id, city_id),
    CONSTRAINT ck_stops_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_stops_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_stops_coordinates
        CHECK ((latitude IS NULL) = (longitude IS NULL))
);

-- 3. Ville de rattachement des lignes
ALTER TABLE lines
    ADD COLUMN IF NOT EXISTS city_id INTEGER;

-- 4. Garantir la cohérence pays / ville
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'uq_lines_id_city'
          AND conrelid = 'public.lines'::regclass
    ) THEN
        ALTER TABLE lines
            ADD CONSTRAINT uq_lines_id_city
            UNIQUE (id, city_id);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_lines_city_country'
          AND conrelid = 'public.lines'::regclass
    ) THEN
        ALTER TABLE lines
            ADD CONSTRAINT fk_lines_city_country
            FOREIGN KEY (city_id, country_id)
            REFERENCES cities(id, country_id);
    END IF;
END
$$;

-- 5. Arrêts ordonnés par ligne
CREATE TABLE IF NOT EXISTS line_stops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id INTEGER NOT NULL,
    city_id INTEGER NOT NULL,
    stop_id INTEGER NOT NULL,
    stop_order INTEGER NOT NULL,
    CONSTRAINT fk_line_stops_line_city
        FOREIGN KEY (line_id, city_id)
        REFERENCES lines(id, city_id),
    CONSTRAINT fk_line_stops_stop_city
        FOREIGN KEY (stop_id, city_id)
        REFERENCES stops(id, city_id),
    CONSTRAINT uq_line_stops_order UNIQUE (line_id, stop_order),
    CONSTRAINT uq_line_stops_stop UNIQUE (line_id, stop_id),
    CONSTRAINT ck_line_stops_order CHECK (stop_order > 0)
);

CREATE INDEX IF NOT EXISTS idx_line_stops_stop
    ON line_stops(stop_id);

COMMIT;

